def _demo_generic_solution(topic: str) -> str:
    return (
        f"# Output for: {topic}\n\n"
        f"This is a demo response from the Omni-Loop Swarm Engine. No live model "
        f"was called. In LIVE mode the full closed-loop pipeline runs against "
        f"your configured provider and the result replaces this stub.\n\n"
        f"Tip: open Settings, paste your API key, pick a model, and switch off "
        f"DEMO mode to see the real pipeline.\n"
    )


def run_demo_pipeline(task: str, *, loop_count: int = 0) -> PipelineResult:
    """Simulate the pipeline. `loop_count` is fixed so tests are deterministic;
    the route can override it for visual variety."""
    started = time.monotonic()
    time.sleep(0.2)  # tiny delay so the UI animation doesn't flash

    topic = _extract_topic(task)
    kind = classify_task(task)
    if kind == "code":
        solution = _demo_code_solution(topic)
    elif kind == "writing":
        solution = _demo_writing_solution(topic)
    elif kind == "analysis":
        solution = _demo_analysis_solution(topic)
    else:
        solution = _demo_generic_solution(topic)

    builder_evidence = (
        f"Produced an initial {kind} deliverable for \"{topic[:80]}\". "
        f"Approach covers the core requirement directly and keeps the implementation self-contained."
    )

    first_decision = "FAIL" if loop_count else "PASS"
    first_evidence = (
        "Missing an edge case for empty input and no error handling around the main path."
        if loop_count
        else "Solution directly satisfies the stated task with no missing requirements found."
    )

    steps: list[AgentStep] = [
        AgentStep(
            name="BUILDER",
            role="builder",
            evidence=builder_evidence,
            payload={"solution": solution},
            elapsed_seconds=0.05,
        ),
        AgentStep(
            name="REVIEWER",
            role="reviewer",
            evidence=first_evidence,
            payload={"decision": first_decision},
            elapsed_seconds=0.04,
        ),
    ]

    if loop_count:
        steps.append(AgentStep(
            name=f"REMEDIATION (loop {loop_count})",
            role="remediation",
            evidence=(
                "Added input validation and a guard clause for the empty-input case; "
                "wrapped the main path in error handling as required by the reviewer."
            ),
            payload={"solution": solution, "loop": loop_count},
            elapsed_seconds=0.06,
        ))
        steps.append(AgentStep(
            name=f"RE-REVIEW (loop {loop_count})",
            role="reviewer",
            evidence="Previously identified issues are resolved. Solution now handles edge cases correctly.",
            payload={"decision": "PASS", "loop": loop_count},
            elapsed_seconds=0.04,
        ))

    steps.append(AgentStep(
        name="MASTER REVIEWER",
        role="master_reviewer",
        evidence=(
            "Solution is complete, addresses the task and constraints, and shows no remaining "
            "production risk. Approved for release."
        ),
        payload={"approval": "GRANTED"},
        elapsed_seconds=0.05,
    ))

    return PipelineResult(
        steps=steps,
        final_output=solution,
        approval="GRANTED",
        loop_count=loop_count,
        tokens={"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0},
        model="demo",
        total_elapsed_seconds=time.monotonic() - started,
    )
