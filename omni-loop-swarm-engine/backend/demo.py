"""
Demo pipeline. No network, no API key. Returns a realistic, task-shaped
response so the UI can be exercised end-to-end.

The demo is now task-aware: it inspects the task text and produces a
plausible deliverable for code, writing, analysis, or generic tasks instead
of always returning the same canned Python snippet.
"""
from __future__ import annotations

import re
import time
from dataclasses import dataclass

from .pipeline import AgentStep, PipelineResult, to_wire


_CODE_HINTS = (
    "function", "code", "implement", "script", "algorithm", "class ",
    "python", "javascript", "typescript", "rust", "go ", "java ", "c++",
    "compile", "debug", "refactor", "module", "library", "api ", "endpoint",
    "sql", "regex", "parse", "html", "css", "react",
)
_WRITING_HINTS = (
    "write", "blog", "essay", "story", "article", "letter", "email",
    "caption", "headline", "tagline", "speech", "press release",
)
_ANALYSIS_HINTS = (
    "analyze", "analyse", "compare", "evaluate", "assess", "review",
    "explain", "summarise", "summarize", "research", "report",
    "strategy", "plan", "swot",
)


def classify_task(task: str) -> str:
    t = task.lower()
    if any(h in t for h in _CODE_HINTS):
        return "code"
    if any(h in t for h in _WRITING_HINTS):
        return "writing"
    if any(h in t for h in _ANALYSIS_HINTS):
        return "analysis"
    return "generic"


def _extract_topic(task: str) -> str:
    """Best-effort topic extraction so the demo feels relevant, not random."""
    # Pull the part after the first verb-ish word if present.
    text = task.strip()
    # Drop a leading "write a ...", "implement a ...", "build a ..."
    m = re.match(
        r"^(?:please\s+)?(?:write|build|implement|create|design|make|generate|develop|craft|draft|analyze|analyse|explain|compare)\s+(?:a|an|the)?\s*(.+)$",
        text,
        re.IGNORECASE,
    )
    if m:
        return m.group(1).strip().rstrip(".!?")
    return text.rstrip(".!?")


def _demo_code_solution(topic: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", topic.lower()).strip("_") or "task"
    return (
        f"# Solution: {topic}\n"
        f"# Generated by the Omni-Loop Swarm demo (no live model was called).\n"
        f"# Switch off DEMO mode and add an API key in Settings to run the\n"
        f"# full Builder -> Reviewer -> Remediation -> Master pipeline against a real model.\n\n"
        f"def solve_{slug}(input_data):\n"
        f'    """Implement the requested behaviour for: {topic}."""\n'
        f"    if not input_data:\n"
        f"        raise ValueError(\"input_data is required\")\n"
        f"    # ...real implementation goes here when running in LIVE mode...\n"
        f"    return input_data\n"
    )


